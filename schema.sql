-- نسخه ۲: صف انتشار و تاریخچه (اجرای یک‌باره در Supabase SQL Editor)
create table if not exists post_queue (
  id bigint generated by default as identity primary key,
  product_id bigint not null,
  status text not null default 'pending' check (status in ('pending','processing','done','failed','cancelled')),
  platform_status jsonb not null default '{}'::jsonb,
  caption_override text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);
create index if not exists post_queue_status_created_idx on post_queue(status, created_at);
create table if not exists post_history (
  id bigint generated by default as identity primary key,
  queue_id bigint,
  product_id bigint,
  product_name text,
  platform text not null,
  success boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists post_history_created_idx on post_history(created_at desc);
alter table post_queue enable row level security;
alter table post_history enable row level security;

